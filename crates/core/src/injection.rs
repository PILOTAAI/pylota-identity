/// A run's fence nonce: 16 Crockford base32 characters. The caller draws it from the platform RNG; core
/// never reads randomness.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Nonce(String);

impl Nonce {
    /// `None` unless `s` is exactly 16 characters of `[0-9A-HJKMNP-TV-Z]`.
    pub fn new(s: &str) -> Option<Nonce> {
        let ok = s.len() == 16
            && s.bytes().all(|b| {
                b.is_ascii_digit()
                    || (b.is_ascii_uppercase() && !matches!(b, b'I' | b'L' | b'O' | b'U'))
            });
        ok.then(|| Nonce(s.to_owned()))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// Escapes one untrusted string before it is fenced (Search §11.6 steps 1–3): control characters other
/// than `\n` and `\t` removed and at most two blank lines in a row; every run of three or more `<` or `>`
/// replaced by as many `‹` or `›`; every occurrence of the nonce replaced by `[nonce]`.
pub fn escape(nonce: &Nonce, content: &str) -> String {
    let cleaned: String = content
        .chars()
        .filter(|&c| !c.is_control() || c == '\n' || c == '\t')
        .collect();
    let mut lines = Vec::new();
    let mut blank = 0;
    for line in cleaned.split('\n') {
        blank = if line.trim().is_empty() { blank + 1 } else { 0 };
        if blank <= 2 {
            lines.push(line);
        }
    }
    let joined = lines.join("\n");

    let chars: Vec<char> = joined.chars().collect();
    let mut out = String::with_capacity(joined.len());
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        let run = chars[i..].iter().take_while(|&&x| x == c).count();
        let glyph = match c {
            '<' if run >= 3 => '‹',
            '>' if run >= 3 => '›',
            _ => c,
        };
        out.extend(std::iter::repeat_n(glyph, run));
        i += run;
    }
    // The nonce alphabet has no `[`, `]` or lower case, so one replacement cannot form a new nonce; the
    // loop is defence in depth.
    while out.contains(nonce.as_str()) {
        out = out.replace(nonce.as_str(), "[nonce]");
    }
    out
}

/// Keeps a service-chosen fence attribute to `[A-Za-z0-9_.:-]`, so it can never carry a marker.
fn attr_safe(s: &str) -> String {
    s.chars()
        .filter(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '.' | ':' | '-'))
        .collect()
}

/// One fenced untrusted string:
/// `<<<MAIL_CONTENT nonce=N field=F k=v>>>escaped<<<END_MAIL_CONTENT nonce=N>>>`. `field` and `attrs` are
/// generated by the service (`attachment_excerpt`, `name=1`).
pub fn fence(nonce: &Nonce, field: &str, attrs: &[(&str, &str)], content: &str) -> String {
    let n = nonce.as_str();
    let mut open = format!("<<<MAIL_CONTENT nonce={n} field={}", attr_safe(field));
    for (k, v) in attrs {
        open.push_str(&format!(" {}={}", attr_safe(k), attr_safe(v)));
    }
    format!(
        "{open}>>>{}<<<END_MAIL_CONTENT nonce={n}>>>",
        escape(nonce, content)
    )
}

/// The reference value that may appear outside a fence, in triage's `FACTS` block and the planner's
/// `why=` line (Inbound › Reference extraction, E1): the upper-cased value when it matches
/// `^[A-Z0-9][A-Z0-9:.+/-]{0,39}$` and `kind` is not `email` or `domain`.
pub fn fact_ref(kind: &str, value: &str) -> Option<String> {
    if matches!(kind, "email" | "domain") {
        return None;
    }
    let v = value.to_uppercase();
    let ok = (1..=40).contains(&v.len())
        && v.bytes().enumerate().all(|(i, b)| {
            b.is_ascii_uppercase()
                || b.is_ascii_digit()
                || (i > 0 && matches!(b, b':' | b'.' | b'+' | b'/' | b'-'))
        });
    ok.then_some(v)
}

/// The `why=` term for a matched reference: `ref:<VALUE>` when [`fact_ref`] accepts it, else
/// `ref:<kind>` alone (the value reaches the model only inside its field's fence).
pub fn why_ref(kind: &str, value: &str) -> String {
    match fact_ref(kind, value) {
        Some(v) => format!("ref:{v}"),
        None => format!("ref:{}", attr_safe(kind)),
    }
}

/// The references of one message, split between the trusted and the fenced part of a model input
/// (Triage §6.2).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct References {
    /// The `FACTS` line: `references: invoice=88213, amount=GBP:412.80`, or `references: none`.
    pub facts: String,
    /// The `field=references` fence holding every refused value as `kind: value` lines, when any.
    pub fenced: Option<String>,
}

/// Splits `(kind, value)` pairs with [`fact_ref`].
pub fn references(nonce: &Nonce, refs: &[(&str, &str)]) -> References {
    let mut facts = Vec::new();
    let mut refused = Vec::new();
    for (kind, value) in refs {
        match fact_ref(kind, value) {
            Some(v) => facts.push(format!("{}={v}", attr_safe(kind))),
            None => refused.push(format!("{}: {value}", attr_safe(kind))),
        }
    }
    References {
        facts: if facts.is_empty() {
            "references: none".to_owned()
        } else {
            format!("references: {}", facts.join(", "))
        },
        fenced: (!refused.is_empty()).then(|| fence(nonce, "references", &[], &refused.join("\n"))),
    }
}

/// A steering signal of [`scan`] (Search §11.9, Screening hold §4.2). `scope_probe` comes from the
/// executor and the two model-only kinds from screening, so neither is here.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Signal {
    InstructionOverride,
    RoleMarker,
    RoleClaim,
    ToolMention,
    FenceSpoof,
    Exfiltration,
    EncodedPayload,
}

/// The fold `scan` matches against: hidden characters removed, NFKC, lower case, the UTS #39 skeleton,
/// lower case again, and every whitespace run as one space (or one `\n` when it holds a line break, so
/// line-start markers survive).
pub fn fold(text: &str) -> String {
    let (visible, _) = strip_hidden_chars(text);
    let nfkc: String = visible.nfkc().collect();
    let skeleton = crate::address::fold(&nfkc.to_lowercase()).to_lowercase();
    let mut out = String::with_capacity(skeleton.len());
    let mut ws: Option<bool> = None;
    for c in skeleton.chars() {
        if c.is_whitespace() {
            ws = Some(ws.unwrap_or(false) || c == '\n');
        } else {
            if let Some(newline) = ws.take() {
                out.push(if newline { '\n' } else { ' ' });
            }
            out.push(c);
        }
    }
    if let Some(newline) = ws {
        out.push(if newline { '\n' } else { ' ' });
    }
    out
}

/// One piece of a pattern. Literal text is stored as data and compiled from its fold, escaped, so regex
/// syntax is never folded and a pattern matches its phrases raw and folded (T52).
enum Part {
    /// A literal phrase; a space matches one folded whitespace run.
    Lit(&'static str),
    /// One of these phrases.
    Alt(&'static [&'static str]),
    /// One of these phrases, or nothing.
    Opt(&'static [&'static str]),
    /// A word boundary.
    B,
    /// The start of a line.
    LineStart,
    /// Up to this many whole words, then a space: "next to".
    Words(u8),
    /// An address or a URL.
    Target,
    /// A base64-looking run of more than 200 characters (a class, not a literal).
    Base64Run,
}

struct Pattern {
    signal: Signal,
    parts: &'static [Part],
    /// Phrases the pattern must match, raw and folded (`t52_confusable_fold`); read by tests only.
    #[cfg_attr(not(test), allow(dead_code))]
    examples: &'static [&'static str],
}

