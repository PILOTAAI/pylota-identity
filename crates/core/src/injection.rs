/// A folded literal as regex: each character escaped, each space one folded whitespace run.
fn lit(s: &str) -> String {
    fold(s)
        .chars()
        .map(|c| match c {
            ' ' | '\n' => "[ \\n]".to_owned(),
            c => regex::escape(&c.to_string()),
        })
        .collect()
}

fn alts(phrases: &[&str]) -> String {
    let v: Vec<String> = phrases.iter().map(|p| lit(p)).collect();
    format!("(?:{})", v.join("|"))
}

fn compile(parts: &[Part]) -> Regex {
    let mut re = String::new();
    for p in parts {
        match p {
            Lit(s) => re.push_str(&lit(s)),
            Alt(a) => re.push_str(&alts(a)),
            Opt(a) => {
                re.push_str(&alts(a));
                re.push('?');
            }
            B => re.push_str(r"\b"),
            Part::LineStart => re.push_str("(?m:^)"),
            Words(n) => re.push_str(&format!(r"(?:[ \n][^ \n]+){{0,{n}}}[ \n]")),
            Part::Target => re.push_str(&format!(
                r"(?:[^\s@]+@[^\s@]+\.[^\s@]+|{}s?{}\S+|{}\S+)",
                lit("http"),
                lit("://"),
                lit("www.")
            )),
            // Folded base64 stays in this class: the skeleton maps `0`, `1`, `I` and `m` to ASCII
            // letters and lower-cases the rest.
            Part::Base64Run => re.push_str(r"[a-z0-9+/]{201,}"),
        }
    }
    Regex::new(&re).expect("fixed pattern")
}

fn compiled() -> &'static [(Signal, Regex)] {
    static C: OnceLock<Vec<(Signal, Regex)>> = OnceLock::new();
    C.get_or_init(|| {
        PATTERNS
            .iter()
            .map(|p| (p.signal, compile(p.parts)))
            .collect()
    })
}

/// The steering signals in one untrusted string, each once, in [`Signal`] order (Search §11.9).
pub fn scan(text: &str) -> Vec<Signal> {
    let folded = fold(text);
    let mut out: Vec<Signal> = compiled()
        .iter()
        .filter(|(_, re)| re.is_match(&folded))
        .map(|&(s, _)| s)
        .collect();
    out.sort();
    out.dedup();
    out
}

